import { expect, test, type Locator, type Page } from '@playwright/test';
import { lessons } from '../../src/content/lessons';
async function wheelIn(page: Page, pane: Locator, delta: number) {
  const box = await pane.boundingBox();
  if (!box) throw new Error('Scroll pane is missing');
  await page.mouse.move(box.x + 8, box.y + box.height / 2);
  await page.mouse.wheel(0, delta);
}
async function plainEditor(page: Page) {
  const toggle = page.getByRole('button', { name: 'Use plain text editor', exact: true });
  if (await toggle.isVisible()) await toggle.click();
  return page.getByRole('textbox', { name: 'SQL query editor', exact: true });
}
test('desktop reading and practice scroll independently with reachable tabs and answers', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto('/');
  await expect(page.getByText('DuckDB ready', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^Module 4:/ }).click();
  await page.getByRole('navigation', { name: 'Module 4 lessons' }).getByRole('button', { name: /Build a cleaned spending report/ }).click();
  await expect(page.getByText('DuckDB ready', { exact: true })).toBeVisible();
  const reading = page.getByRole('article', { name: 'Lesson content', exact: true });
  const practice = page.getByRole('region', { name: 'Practice workspace', exact: true });
  const tabs = page.getByRole('tablist', { name: 'Lesson view' });
  const sql = lessons[31].solution;
  await (await plainEditor(page)).fill(sql);
  const editorTop = (await page.locator('.editor-resizable').boundingBox())!.y;
  expect(await reading.evaluate(element => element.scrollHeight - element.clientHeight)).toBeGreaterThan(0);
  await wheelIn(page, reading, 1600);
  await expect.poll(() => reading.evaluate(element => element.scrollTop), { timeout: 5000 }).toBeGreaterThan(0);
  expect(await practice.evaluate(element => element.scrollTop)).toBe(0);
  expect((await page.locator('.editor-resizable').boundingBox())!.y).toBe(editorTop);
  expect(await page.evaluate(() => window.scrollY)).toBe(0);
  await expect(reading.getByRole('heading', { name: 'Final help: the complete answer' })).toBeInViewport();
  await reading.getByRole('button', { name: 'Reveal solution', exact: true }).click();
  await expect(reading.locator('#complete-answer pre code')).toHaveText(sql);
  const readingScroll = await reading.evaluate(element => element.scrollTop);
  await page.getByRole('tab', { name: 'Visual', exact: true }).click();
  await wheelIn(page, practice, 1800);
  await expect.poll(() => practice.evaluate(element => element.scrollTop), { timeout: 5000 }).toBeGreaterThan(0);
  expect(await reading.evaluate(element => element.scrollTop)).toBe(readingScroll);
  const practiceBox = (await practice.boundingBox())!;
  const tabsBox = (await tabs.boundingBox())!;
  expect(Math.abs(tabsBox.y - practiceBox.y)).toBeLessThan(3);
  await page.getByRole('tab', { name: 'Terminal', exact: true }).click();
  await expect.poll(() => practice.evaluate(element => element.scrollTop), { timeout: 5000 }).toBe(0);
  await wheelIn(page, practice, 1800);
  await expect.poll(() => practice.evaluate(element => element.scrollTop), { timeout: 5000 }).toBeGreaterThan(0);
  await expect(tabs).toBeInViewport();
  expect(await reading.evaluate(element => element.scrollTop)).toBe(readingScroll);
  await page.getByRole('combobox', { name: 'Colour theme' }).selectOption('light');
  await page.screenshot({ path: 'test-results/workspace-desktop-light.png' });
  await page.getByRole('combobox', { name: 'Colour theme' }).selectOption('dark');
  await page.screenshot({ path: 'test-results/workspace-desktop-dark.png' });
  await reading.getByRole('button', { name: 'Load solution into editor', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'SQL editor', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect.poll(() => practice.evaluate(element => element.scrollTop), { timeout: 5000 }).toBe(0);
  await expect(await plainEditor(page)).toHaveValue(sql);
  await page.getByRole('button', { name: 'Run Query', exact: true }).click();
  await expect(page.getByText(/Correct —/)).toBeVisible();
  await page.getByRole('button', { name: 'View dashboard', exact: true }).scrollIntoViewIfNeeded();
  await expect(page.getByRole('button', { name: 'View dashboard', exact: true })).toBeInViewport();
  await expect(tabs).toBeInViewport();
  await page.getByRole('tab', { name: 'SQL editor', exact: true }).click();
  await reading.focus(); await page.keyboard.press('Home');
  await expect.poll(() => reading.evaluate(element => element.scrollTop), { timeout: 5000 }).toBe(0);
  await page.keyboard.press('PageDown');
  await expect.poll(() => reading.evaluate(element => element.scrollTop), { timeout: 5000 }).toBeGreaterThan(0);
  expect(await practice.evaluate(element => element.scrollTop)).toBe(0);
  await page.setViewportSize({ width: 1280, height: 800 });
  expect(await reading.evaluate(element => getComputedStyle(element).overflowY)).toBe('auto');
  await expect(tabs).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test('short, narrow and mobile windows retain ordinary page scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 600 });
  await page.goto('/');
  const reading = page.getByRole('article', { name: 'Lesson content', exact: true });
  const practice = page.getByRole('region', { name: 'Practice workspace', exact: true });
  await expect(page.getByRole('heading', { name: 'Understanding tables and SELECT', exact: true })).toBeVisible();
  expect(await reading.evaluate(element => getComputedStyle(element).overflowY)).toBe('visible');
  expect(await practice.evaluate(element => getComputedStyle(element).overflowY)).toBe('hidden');
  await page.getByRole('button', { name: 'Reveal solution', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(0);
  await page.screenshot({ path: 'test-results/workspace-short-window.png' });
  await page.setViewportSize({ width: 1100, height: 900 });
  expect(await reading.evaluate(element => getComputedStyle(element).overflowY)).toBe('visible');
  const left = (await reading.boundingBox())!, right = (await practice.boundingBox())!;
  expect(right.y).toBeGreaterThan(left.y + left.height - 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await reading.getByRole('button', { name: 'Reveal solution', exact: true }).click();
  await expect(reading.locator('#complete-answer')).toBeVisible();
  await reading.getByRole('button', { name: 'Load solution into editor', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'SQL editor', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/workspace-mobile.png' });
});
