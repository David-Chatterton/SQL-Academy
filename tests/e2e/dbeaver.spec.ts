import { expect, test, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { nativeSeedSQL } from '../../src/data/finance';
async function plainEditor(page: Page) {
  const toggle = page.getByRole('button', { name: 'Use plain text editor', exact: true });
  if (await toggle.isVisible()) await toggle.click();
  return page.getByRole('textbox', { name: 'SQL query editor', exact: true });
}
test('DBeaver guide provides matching downloads, keyboard tabs and module-specific GUI setup', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto('/');
  await expect(page.getByText('DuckDB ready', { exact: true })).toBeVisible();
  const draft = 'SELECT id, payee FROM transactions LIMIT 3;';
  await (await plainEditor(page)).fill(draft);
  await page.getByRole('tab', { name: 'SQL editor', exact: true }).focus();
  await page.keyboard.press('End');
  const tab = page.getByRole('tab', { name: 'DBeaver', exact: true });
  await expect(tab).toHaveAttribute('aria-selected', 'true');
  await expect(tab).toBeFocused();
  const guide = page.getByRole('tabpanel', { name: 'DBeaver', exact: true });
  await expect(guide.getByRole('heading', { name: 'Explore the practice database in DBeaver', exact: true })).toBeVisible();
  await expect(guide).toContainText('academy.duckdb');
  await expect(guide).toContainText('SQL Editor → Execute SQL Script');
  await expect(guide).toContainText('DBeaver results and edits do not synchronise with this course.');
  const seedDownload = page.waitForEvent('download');
  await guide.getByRole('button', { name: 'Download matching training.sql', exact: true }).click();
  const seed = await seedDownload;
  expect(seed.suggestedFilename()).toBe('training.sql');
  expect(await readFile(await seed.path(), 'utf8')).toBe(nativeSeedSQL());
  await expect(guide.locator('.sql-block')).toBeHidden();
  await guide.getByText('Show starter queries for Modules 1–3', { exact: true }).click();
  await expect(guide.locator('.sql-block')).toContainText('Expected: 10000');
  await guide.getByRole('link', { name: 'DuckDB file access', exact: true }).scrollIntoViewIfNeeded();
  await expect(tab).toBeInViewport();
  await page.getByRole('combobox', { name: 'Colour theme' }).selectOption('light');
  await page.getByRole('region', { name: 'Practice workspace', exact: true }).evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: 'test-results/dbeaver-desktop-light.png' });
  await page.getByRole('combobox', { name: 'Colour theme' }).selectOption('dark');
  await page.screenshot({ path: 'test-results/dbeaver-desktop-dark.png' });
  await tab.focus(); await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Visual', exact: true })).toBeFocused();
  await page.keyboard.press('ArrowLeft');
  await expect(tab).toBeFocused();
  await page.keyboard.press('ArrowLeft');
  await expect(page.getByRole('tab', { name: 'Terminal', exact: true })).toBeFocused();
  await page.keyboard.press('Home');
  await expect(page.getByRole('tab', { name: 'Visual', exact: true })).toBeFocused();
  await page.getByRole('tab', { name: 'SQL editor', exact: true }).click();
  await expect(await plainEditor(page)).toHaveValue(draft);
  await page.setViewportSize({ width: 320, height: 800 });
  await tab.click();
  await expect(tab).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Open course navigation', exact: true }).click();
  await page.getByRole('button', { name: /^Module 4:/ }).click();
  await page.getByRole('navigation', { name: 'Module 4 lessons' }).getByRole('button', { name: /Import a CSV without losing/ }).click();
  await expect(page.getByText('DuckDB ready', { exact: true })).toBeVisible();
  await tab.click();
  await expect(guide).toContainText('cleaning.duckdb');
  await expect(guide).toContainText('raw_statement');
  await expect(guide).toContainText('full local paths in DBeaver');
  await expect(guide.getByRole('button', { name: 'Download matching training.sql', exact: true })).toHaveCount(0);
  const setupDownload = page.waitForEvent('download');
  await guide.getByRole('button', { name: 'Download DBeaver cleaning setup', exact: true }).click();
  const setup = await setupDownload;
  expect(setup.suggestedFilename()).toBe('dbeaver-cleaning-setup.sql');
  const sql = await readFile(await setup.path(), 'utf8');
  expect(sql).toContain("FROM read_csv('/absolute/path/to/statement.csv', header = true, all_varchar = true)");
  expect(sql).toContain('CREATE VIEW clean_candidates');
  expect(sql).toContain('COMMIT;');
  expect(sql).not.toContain('COPY (');
  expect(sql).not.toContain('.read');
  expect(await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('duckdb-academy:progress:v1')!).completed).length)).toBe(0);
  await page.getByRole('combobox', { name: 'Colour theme' }).selectOption('light');
  await tab.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/dbeaver-mobile-light.png' });
  await page.getByRole('combobox', { name: 'Colour theme' }).selectOption('dark');
  await tab.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/dbeaver-mobile-dark.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
